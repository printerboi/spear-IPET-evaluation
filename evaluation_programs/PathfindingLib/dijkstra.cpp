int main() {
    // Create a grid with fixed tiles
    Pathfinding_Grid<int> grid(gridWidth, gridHeight);

    // Read the grid and set walkable if the tile is 0
    for (int y = 0; y < gridHeight; ++y) {
        for (int x = 0; x < gridWidth; ++x) {
            const bool isWalkable = (mazeGrid[y][x] == 0);
            if(isWalkable) {
                grid.setWalkable(x, y);
            }
        }
    }

    // Define start and end tile.
    auto start = std::make_tuple(0, 0);
    auto end = std::make_tuple(gridWidth - 1, gridHeight - 1);

    // Call Dijkstra on the weighted grid.
    auto path = findPathDijkstra(grid, start, end);

    // Print the path.
    if (!path.empty()) {
        std::cout << "Path found with " << path.size() << " steps:\n";

        int totalPathCost = 0;

        for (const auto& [x, y] : path) {
            std::cout << "(" << x << "," << y << ") ";
        }

        std::cout << "\nTotal path cost: " << totalPathCost << "\n";
    } else {
        std::cout << "No path found!\n";
    }

    return 0;
}